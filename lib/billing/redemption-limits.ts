/**
 * 兑换码发放上限。
 *
 * 单独成模块是因为服务端动作文件（`"use server"`）只能导出 async 函数，
 * 常量放那里客户端表单就 import 不了；而前端要拿同一份数值去设 `max` 与提示文案，
 * 免得出现「界面能填、保存被拒」。
 */

/**
 * 单码额度上限（cr）。站点日常量级：注册奖励 2,000 / 每日签到 ~90 / 真实充值 3,394 cr，
 * 10 万已经极宽。加这条校验的起因是线上曾发出过 1,000,000,000 cr 的码（已兑换）与
 * 两个 1,000,000 cr 的码——此前服务端只校验 `quota > 0`，一次手滑就能造出天文数字的站点负债。
 */
export const MAX_REDEMPTION_QUOTA = 100_000;

/** 单码最大可兑换次数；与额度上限相乘即单码理论最大发放量（10 万 × 1000 = 1 亿 cr）。 */
export const MAX_REDEMPTION_USES = 1_000;
