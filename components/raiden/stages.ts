/**
 * 雷电行动的五个关卡：敌人波次时间轴、Boss 数值与主题。
 *
 * 时间轴按「开局后秒数」写死，方便调难度；`components/raiden/engine.ts`
 * 只负责在对应时间点把描述变成实体。所有坐标都在 480×720 的逻辑画布内。
 *
 * 难度递增靠三件事：波次更密更早、精英比例更高、Boss 血量与弹幕更快；
 * 主题（background.ts）与 Boss 行为（engine.ts 里按 `no` 分派）同步换。
 */

import type { BulletType } from "./weapons";

export type StageTheme = "coast" | "city" | "orbit" | "lunar" | "void";
export type EnemyKind = "drone" | "gunship" | "turret" | "tank" | "heli";
/** 补给字母：五种子弹类型 + 炸弹。 */
export type PowerType = BulletType | "B";

export interface EnemySpawn {
  at: number;
  kind: EnemyKind;
  x: number;
  /** 精英机：血更厚、分更高，必掉补给。 */
  elite?: boolean;
  drop?: PowerType;
  dir?: 1 | -1;
}

export interface StageBoss {
  hp: number;
  score: number;
  name: string;
  title: string;
}

export interface StageDef {
  no: number;
  name: string;
  subtitle: string;
  theme: StageTheme;
  /** 第几秒 Boss 入场；之前按时间轴出怪。 */
  bossAt: number;
  boss: StageBoss;
  spawns: EnemySpawn[];
  /** 地面单位随卷轴下移的速度（px/s）。 */
  groundSpeed: number;
}

function wave(
  at: number,
  kind: EnemyKind,
  xs: number[],
  opts: Omit<EnemySpawn, "at" | "kind" | "x"> = {},
): EnemySpawn[] {
  return xs.map((x, i) => ({ at: at + i * 0.16, kind, x, ...opts }));
}

